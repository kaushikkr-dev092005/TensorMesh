// Run the existing synthetic-model GPU checks through Deno's standalone runtime.
// This avoids the test-runner pipe and browser-launch restrictions; it does not
// verify browser transport, native Rust inference, or real model logit parity.
// deno run --unstable-webgpu --allow-read --allow-env tests/engine_synth_deno.js /path/model.gguf
import { pathToFileURL } from "node:url";
import { pageMain } from "./e2e/engine_synth.mjs";
if (!Deno.args[0]) throw new Error("Pass the synthetic GGUF path generated by tests/e2e/synth.mjs");
const result = await pageMain({
  modelUrl: pathToFileURL(Deno.args[0]).href,
  moduleBase: new URL("../", import.meta.url).href.replace(/\/$/, ""),
  tokens: 40, cols: [4, 16], ks: [1, 3, 7], wg: 64, noSplit: false, kvQ8: false,
});
const failures = result.results.filter(check => !check.ok);
console.log(JSON.stringify({checks: result.results.length, failures: failures.length, scope: "synthetic GGUF / standalone JS WebGPU"}));
Deno.exit(failures.length ? 1 : 0);
